function record(
  id: string,
  name: string,
  family: string,
  architecture: string,
  process: string,
  basis: string,
  page: number,
  section: string,
  schema: string[][],
  values: string[],
  flags: Record<string, string> = {},
  note?: string,
): Material {
  if (schema.length !== values.length)
    throw new Error(`Incomplete source transcription: ${id}`);
  return {
    id,
    name,
    family,
    architecture,
    process,
    basis,
    page,
    section,
    note,
    properties: schema.map(([symbol, label, unit], i) => ({
      symbol,
      label,
      unit,
      value: values[i],
      review: flags[symbol],
    })),
  };
}
